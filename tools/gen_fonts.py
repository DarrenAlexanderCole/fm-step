#!/usr/bin/env python3
"""Pre-rasterise Inter (SIL Open Font License) into 8-bit coverage glyphs for
the MPC screen, so the app needs no font engine. Writes internal/gfx/fonts_gen.go.
Usage: gen_fonts.py [inter dir]"""
import os, sys
from PIL import ImageFont

D = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/opentype/inter/"
SPECS = [  # Go name, file, pixel size
    ("Small", "Inter-Bold.otf", 7),
    ("Label", "Inter-Bold.otf", 7),
    ("Body", "Inter-Bold.otf", 9),
    ("Value", "Inter-SemiBold.otf", 11),
    ("Title", "Inter-SemiBold.otf", 12),
    ("Big", "InterDisplay-Bold.otf", 16),
]
CHARS = [chr(c) for c in range(32, 127)] + ["·", "▶", "■", "°"]

out = ["// Code generated by tools/gen_fonts.py from Inter (SIL OFL 1.1). DO NOT EDIT.", "", "package gfx", ""]
for name, file, size in SPECS:
    f = ImageFont.truetype(os.path.join(D, file), size)
    asc, desc = f.getmetrics()
    capb = f.getbbox("H")
    cap = capb[3] - capb[1]
    glyphs = []
    for ch in CHARS:
        try:
            mask = f.getmask(ch, mode="L")
        except Exception:
            continue
        bb = f.getbbox(ch)  # relative to the ascender-top origin
        w, h = mask.size
        adv = f.getlength(ch)
        data = bytes(mask)
        glyphs.append((ord(ch), adv, bb[0], bb[1], w, h, data))
    out.append(f"var {name} = &Font{{Ascent: {asc}, Descent: {desc}, Cap: {cap}, CapTop: {capb[1]}, Glyphs: map[rune]Glyph{{")
    for code, adv, x0, y0, w, h, data in glyphs:
        hexs = data.hex()
        out.append(f"\t{code}: {{Adv: {adv:.3f}, X: {x0}, Y: {y0}, W: {w}, H: {h}, Cov: \"{''.join('\\x' + hexs[i:i+2] for i in range(0, len(hexs), 2))}\"}},")
    out.append("}}")
    out.append("")
open(os.path.join(os.path.dirname(__file__), "..", "internal", "gfx", "fonts_gen.go"), "w").write("\n".join(out))
print("ok", len(SPECS), "fonts")
